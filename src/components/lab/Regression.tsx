"use client";

import { useMemo, useState } from "react";
import { CartesianGrid, ComposedChart, ErrorBar, Line, ReferenceLine, ResponsiveContainer, Scatter, XAxis, YAxis } from "recharts";
import { generateData, olsFit, type SyntheticParams } from "@/lib/econ/regression";
import { ModelLayout, Note, Slider, Stat, Tex, chartColors, fmt } from "./controls";

export function Regression() {
  const [p, setP] = useState<SyntheticParams>({ n: 40, beta0: 2, beta1: 1.5, noiseSd: 3, seed: 7, outlier: false });
  const [showResiduals, setShowResiduals] = useState(true);
  const set = (patch: Partial<SyntheticParams>) => setP((x) => ({ ...x, ...patch }));

  const data = useMemo(() => generateData(p), [p]);
  const fit = useMemo(() => olsFit(data), [data]);

  const points = useMemo(
    () =>
      data.map((d, i) => {
        const e = fit ? fit.residuals[i] : 0;
        return { x: d.x, y: d.y, err: [Math.max(e, 0), Math.max(-e, 0)] as [number, number] };
      }),
    [data, fit],
  );
  const resid = useMemo(
    () => (fit ? data.map((d, i) => ({ fitted: fit.intercept + fit.slope * d.x, e: fit.residuals[i] })) : []),
    [data, fit],
  );

  if (!fit) return <Note>Not enough variation to fit a line. Increase the number of observations.</Note>;

  const ys = data.map((d) => d.y);
  const yLo = Math.floor(Math.min(...ys, p.beta0) - 2);
  const yHi = Math.ceil(Math.max(...ys, p.beta0 + 10 * p.beta1) + 2);
  const fitLine = [0, 10].map((x) => ({ x, y: fit.intercept + fit.slope * x }));
  const trueLine = [0, 10].map((x) => ({ x, y: p.beta0 + p.beta1 * x }));

  return (
    <ModelLayout
      chart={
        <>
          <p className="mb-3 rounded-lg border border-warn/40 bg-warn/10 px-3 py-2 text-sm">
            Synthetic data. These points are generated by the sliders to illustrate the method. They are not empirical evidence.
          </p>
          <div role="img" aria-label={`Scatterplot of ${fit.n} synthetic points with the fitted line. Estimated slope ${fmt(fit.slope)}, R squared ${fmt(fit.r2)}.`} className="h-[380px] w-full sm:h-[440px]">
            <ResponsiveContainer width="100%" height="100%">
              <ComposedChart margin={{ top: 10, right: 16, bottom: 28, left: 8 }}>
                <CartesianGrid stroke={chartColors.grid} />
                <XAxis type="number" dataKey="x" domain={[0, 10]} allowDataOverflow tick={{ fill: chartColors.axis, fontSize: 12 }} label={{ value: "x (explanatory variable)", position: "insideBottom", offset: -16, fill: chartColors.axis, fontSize: 12 }} />
                <YAxis type="number" dataKey="y" domain={[yLo, yHi]} allowDataOverflow tick={{ fill: chartColors.axis, fontSize: 12 }} tickFormatter={(v) => fmt(v, 0)} label={{ value: "y (outcome)", angle: -90, position: "insideLeft", fill: chartColors.axis, fontSize: 12 }} />
                <Line data={trueLine} dataKey="y" stroke={chartColors.axis} strokeDasharray="6 5" strokeWidth={1.6} dot={false} isAnimationActive={false} />
                <Scatter data={points} dataKey="y" fill={chartColors.cyan} fillOpacity={0.8} isAnimationActive={false}>
                  {showResiduals && p.n <= 80 && <ErrorBar dataKey="err" direction="y" width={0} stroke={chartColors.warn} strokeWidth={1} />}
                </Scatter>
                <Line data={fitLine} dataKey="y" stroke={chartColors.blue} strokeWidth={2.8} dot={false} isAnimationActive={false} />
              </ComposedChart>
            </ResponsiveContainer>
          </div>
          <ul className="mt-3 flex flex-wrap gap-x-5 gap-y-1 text-xs text-muted">
            <li><span className="mr-1.5 inline-block h-0.5 w-5 bg-accent align-middle" />Fitted line (OLS)</li>
            <li><span className="mr-1.5 inline-block h-0.5 w-5 border-t border-dashed border-muted align-middle" />True line used to generate the data</li>
            {showResiduals && p.n <= 80 && <li><span className="mr-1.5 inline-block h-3 w-0.5 bg-warn align-middle" />Residuals</li>}
          </ul>

          <h3 className="mt-6 text-sm text-muted">Residuals against fitted values</h3>
          <div role="img" aria-label="Residual plot. Points scattered randomly around zero suggest the straight-line model fits well." className="mt-2 h-[200px] w-full">
            <ResponsiveContainer width="100%" height="100%">
              <ComposedChart margin={{ top: 6, right: 16, bottom: 22, left: 8 }}>
                <CartesianGrid stroke={chartColors.grid} />
                <XAxis type="number" dataKey="fitted" domain={["auto", "auto"]} tick={{ fill: chartColors.axis, fontSize: 11 }} tickFormatter={(v) => fmt(v, 0)} label={{ value: "Fitted value", position: "insideBottom", offset: -12, fill: chartColors.axis, fontSize: 11 }} />
                <YAxis type="number" dataKey="e" tick={{ fill: chartColors.axis, fontSize: 11 }} tickFormatter={(v) => fmt(v, 0)} />
                <ReferenceLine y={0} stroke={chartColors.axis} />
                <Scatter data={resid} fill={chartColors.warn} fillOpacity={0.75} isAnimationActive={false} />
              </ComposedChart>
            </ResponsiveContainer>
          </div>
        </>
      }
      controls={
        <>
          <p className="text-sm text-muted">
            Data are generated as <Tex>{"y = \\beta_0 + \\beta_1 x + \\varepsilon"}</Tex>, with x between 0 and 10 and the error normally distributed.
          </p>
          <Slider label="Observations n" value={p.n} min={5} max={200} step={5} onChange={(n) => set({ n })} />
          <Slider label="True intercept β₀" value={p.beta0} min={-10} max={10} step={0.5} onChange={(beta0) => set({ beta0 })} />
          <Slider label="True slope β₁" value={p.beta1} min={-5} max={5} step={0.1} onChange={(beta1) => set({ beta1 })} />
          <Slider label="Noise (error std. dev.)" value={p.noiseSd} min={0} max={10} step={0.5} onChange={(noiseSd) => set({ noiseSd })} />
          <div className="flex flex-wrap gap-2">
            <button type="button" onClick={() => set({ seed: p.seed + 1 })} className="rounded-full border border-line-strong px-4 py-2 text-sm transition-colors hover:bg-line">
              Draw a new sample
            </button>
            <button type="button" aria-pressed={p.outlier} onClick={() => set({ outlier: !p.outlier })} className={`rounded-full border px-4 py-2 text-sm transition-colors ${p.outlier ? "border-warn bg-warn/15" : "border-line-strong hover:bg-line"}`}>
              {p.outlier ? "Remove outlier" : "Add an outlier"}
            </button>
          </div>
          <label className="flex items-center gap-2 text-sm">
            <input type="checkbox" checked={showResiduals} onChange={(e) => setShowResiduals(e.target.checked)} className="size-4 accent-[var(--accent)]" />
            Show residual segments (up to 80 points)
          </label>
          <p className="text-xs text-muted">Sample number {p.seed}. The same number always gives the same data.</p>
        </>
      }
      below={
        <div className="grid gap-6 lg:grid-cols-2">
          <section className="glass rounded-3xl p-6" aria-labelledby="rg-est">
            <h2 id="rg-est" className="display text-2xl">
              Estimates
            </h2>
            <dl className="mt-4 grid grid-cols-2 gap-3 sm:grid-cols-3">
              <Stat label="Estimated slope β̂₁" value={fmt(fit.slope, 3)} />
              <Stat label="Estimated intercept β̂₀" value={fmt(fit.intercept, 3)} />
              <Stat label="R-squared" value={fmt(fit.r2, 3)} />
              <Stat label="Std. error of slope" value={fmt(fit.seSlope, 3)} />
              <Stat label="t-statistic (slope)" value={fmt(fit.tSlope, 2)} />
              <Stat label="Residual std. error" value={fmt(fit.sigma, 3)} />
            </dl>
            <p className="mt-4 text-sm leading-relaxed text-muted">
              The true slope is {fmt(p.beta1)} and the estimate is {fmt(fit.slope, 3)}. Draw new samples to see how the estimate varies from sample to sample; a larger n or smaller noise makes it more stable.
              {p.outlier && " The added outlier pulls the fitted line toward itself, which shows why least squares is sensitive to extreme points."}
            </p>
          </section>
          <section className="glass rounded-3xl p-6" aria-labelledby="rg-how">
            <h2 id="rg-how" className="display text-2xl">
              How it is calculated
            </h2>
            <ol className="mt-4 grid gap-3 text-sm leading-relaxed text-muted">
              <li>
                OLS minimises the sum of squared residuals, which gives <Tex>{"\\hat\\beta_1 = \\dfrac{\\sum (x_i-\\bar x)(y_i-\\bar y)}{\\sum (x_i-\\bar x)^2}"}</Tex> and <Tex>{"\\hat\\beta_0 = \\bar y - \\hat\\beta_1 \\bar x"}</Tex>.
              </li>
              <li>
                <Tex>{"R^2 = 1 - \\dfrac{SSR}{SST}"}</Tex> is the share of the variation in y that the line explains.
              </li>
              <li>
                The standard error of the slope is <Tex>{"\\hat\\sigma / \\sqrt{\\sum (x_i-\\bar x)^2}"}</Tex> with <Tex>{"\\hat\\sigma^2 = SSR/(n-2)"}</Tex>. The t-statistic is the slope divided by this.
              </li>
            </ol>
          </section>
          <div className="lg:col-span-2">
            <Note>
              This page uses simulated data so the true relationship is known. Real research has to deal with omitted variables, measurement error and non-random selection, none of which appear here. A high R-squared does not show that x causes y.
            </Note>
          </div>
        </div>
      }
    />
  );
}
